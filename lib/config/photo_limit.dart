/// 한 게시물에 담을 수 있는 사진 장수 상한.
///
/// 값을 **시스템 사진 선택기에 그대로 넘긴다** — 그래서 사용자는 초과분을 고를
/// 수조차 없다(Android `PickMultipleVisualMedia`, iOS `PHPickerViewController`
/// 의 `selectionLimit`). 다 고른 뒤에 거절당하는 흐름을 만들지 않기 위해서다.
///
/// **30장인 이유.** 자매 앱(모모앨범)에서 상한이 없던 시절 한 번에 71장을 고른
/// 사례가 있었고, 그때 미리보기 썸네일 71장이 전부 원본 해상도로 펼쳐져
/// 아이폰이 죽었다. 카카오톡과 같은 숫자라 국내 사용자에게 익숙하고, 더 올리고
/// 싶으면 게시물을 나누면 된다.
///
/// ⚠️ 이 값을 올리려면 미리보기의 `cacheWidth` 가 그대로 버티는지 먼저 볼 것.
/// 장수 자체보다 **장수 × 한 장당 비용**이 문제였다 — 12MP 사진 한 장을 원본
/// 해상도로 디코딩하면 4032×3024×4 ≈ 49MB 다.
class PhotoLimit {
  PhotoLimit._();

  /// 한 번에 고를 수 있는 사진 장수.
  static const int perPost = 30;
}
